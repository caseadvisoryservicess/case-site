#!/bin/sh
# Проверка переадресации caseadvisory.uz на .com.
#
# Запускать НЕ на сервере, а со своего компьютера (Терминал на Mac, PowerShell с
# curl или Git Bash на Windows): смысл проверки в том, чтобы увидеть домен снаружи,
# глазами обычного посетителя.
#
# Скрипт не чинит ничего, только показывает, на каком шаге всё останавливается.
# Каждый блок отвечает на один вопрос, и вопросы идут в том порядке, в каком их
# задаёт браузер: сначала адрес, потом сертификат, и только потом переадресация.

DOM_UZ=caseadvisory.uz
DOM_COM=caseadvisory.com

echo "=============================================="
echo " 1. Куда указывают домены"
echo "=============================================="
for d in $DOM_UZ www.$DOM_UZ $DOM_COM; do
  ip=$(dig +short "$d" 2>/dev/null | tail -1)
  [ -z "$ip" ] && ip=$(host "$d" 2>/dev/null | awk '/address/{print $NF; exit}')
  echo "  $d  ->  ${ip:-НЕ РАЗРЕШАЕТСЯ}"
done
echo "  Ожидается: .uz на 95.46.96.13, .com на 185.215.4.52"

echo
echo "=============================================="
echo " 2. Сертификат .uz: жив ли и на какие имена"
echo "=============================================="
echo | openssl s_client -connect $DOM_UZ:443 -servername $DOM_UZ 2>/dev/null \
  | openssl x509 -noout -subject -dates -ext subjectAltName 2>/dev/null \
  || echo "  !! Сертификат не отдаётся. Это и есть причина: до правил переадресации"
echo "  Если срок в 'notAfter' уже прошёл или в списке имён нет www.$DOM_UZ -"
echo "  браузер оборвёт соединение ДО того, как сервер успеет перенаправить."

echo
echo "=============================================="
echo " 3. Переадресация по http (без сертификата)"
echo "=============================================="
echo "--- http://$DOM_UZ/"
curl -sS -m 15 -o /dev/null -D - "http://$DOM_UZ/" 2>&1 | grep -iE "^HTTP/|^location:"
echo "--- http://www.$DOM_UZ/"
curl -sS -m 15 -o /dev/null -D - "http://www.$DOM_UZ/" 2>&1 | grep -iE "^HTTP/|^location:"
echo "  Ожидается: 301 или 302 и Location на https://$DOM_COM/"
echo "  Если здесь ответ 200 - правило вообще не срабатывает (см. mod_rewrite ниже)."

echo
echo "=============================================="
echo " 4. Переадресация по https"
echo "=============================================="
curl -sS -m 15 -o /dev/null -D - "https://$DOM_UZ/" 2>&1 | grep -iE "^HTTP/|^location:|SSL|certificate"
echo "  Ошибка сертификата на этом шаге при рабочем шаге 3 означает:"
echo "  правило в порядке, сломан сертификат."

echo
echo "=============================================="
echo " 5. Платформа обязана остаться на .uz"
echo "=============================================="
curl -sS -m 20 -o /dev/null -D - "https://$DOM_UZ/os/" 2>&1 | grep -iE "^HTTP/|^location:"
echo "  Ожидается: 200 и НИ ОДНОГО Location. Если тут Location на .com -"
echo "  исключение для /os не работает, и платформа недоступна."

echo
echo "=============================================="
echo " 6. Продление сертификата не перехвачено"
echo "=============================================="
curl -sS -m 15 -o /dev/null -D - "http://$DOM_UZ/.well-known/acme-challenge/probe" 2>&1 | grep -iE "^HTTP/|^location:"
echo "  Ожидается: 404 (файла нет - это нормально)."
echo "  Если Location на .com - продление сертификата сломано, и домен умрёт"
echo "  в течение 90 дней, даже если сегодня всё открывается."

echo
echo "=============================================="
echo " 7. Работает ли mod_rewrite на хостинге"
echo "=============================================="
echo "  На сервере через Менеджер файлов создайте"
echo "  /domains/$DOM_UZ/public_html/rwtest.php с одной строкой:"
echo "    <?php echo in_array('mod_rewrite', apache_get_modules()) ? 'ЕСТЬ' : 'НЕТ';"
echo "  и откройте http://$DOM_UZ/rwtest.php (после проверки файл удалите)."
echo "  'НЕТ' объясняет всё: RewriteEngine молча ничего не делает, а старое"
echo "  правило Redirect 301 работало, потому что это другой модуль - mod_alias."
